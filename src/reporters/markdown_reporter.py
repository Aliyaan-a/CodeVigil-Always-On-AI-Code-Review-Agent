"""Markdown report output — ideal for PR comments."""

from __future__ import annotations

from pathlib import Path

from src.schemas.findings import Finding, ReviewReport, Severity

SEVERITY_EMOJI = {
    Severity.INFO: "ℹ️",
    Severity.WARNING: "⚠️",
    Severity.ERROR: "❌",
    Severity.CRITICAL: "🔴",
}


class MarkdownReporter:
    """Renders a ReviewReport as Markdown — suitable for PR comments."""

    def render(self, report: ReviewReport, output_path: str | None = None) -> str:
        sections = [
            self._header(report),
            self._score_section(report),
            self._summary_table(report),
            self._findings_section(report),
            self._metrics_section(report),
            self._footer(report),
        ]
        md = "\n\n".join(s for s in sections if s)

        if output_path:
            Path(output_path).write_text(md, encoding="utf-8")
        return md

    def _header(self, report: ReviewReport) -> str:
        return (
            f"# 🔍 CodeVigil Review\n\n"
            f"**Project:** `{report.project_name}`  \n"
            f"**Files analyzed:** {len(report.files_analyzed)}  \n"
            f"**Analysis time:** {report.analysis_duration_ms:.0f}ms"
        )

    def _score_section(self, report: ReviewReport) -> str:
        if report.score is None:
            return ""

        s = report.score
        return (
            f"## Score: {s.grade} ({s.overall}/100)\n\n"
            f"| Dimension | Score |\n"
            f"|-----------|-------|\n"
            f"| Security | {s.security}/100 |\n"
            f"| Reliability | {s.reliability}/100 |\n"
            f"| Maintainability | {s.maintainability}/100 |\n"
            f"| Style | {s.style}/100 |"
        )

    def _summary_table(self, report: ReviewReport) -> str:
        counts = report.findings_by_severity
        if not counts:
            return "## ✅ No issues found!"

        rows = []
        for sev in [Severity.CRITICAL, Severity.ERROR, Severity.WARNING, Severity.INFO]:
            count = counts.get(sev.value, 0)
            if count > 0:
                emoji = SEVERITY_EMOJI.get(sev, "")
                rows.append(f"| {emoji} {sev.value.capitalize()} | {count} |")

        if not rows:
            return ""

        return (
            "## Findings Summary\n\n"
            "| Severity | Count |\n"
            "|----------|-------|\n"
            + "\n".join(rows)
        )

    def _findings_section(self, report: ReviewReport) -> str:
        findings = report.all_findings
        if not findings:
            return ""

        lines = ["## Detailed Findings\n"]

        by_file: dict[str, list[Finding]] = {}
        for f in findings:
            by_file.setdefault(f.location.file_path, []).append(f)

        for file_path, file_findings in by_file.items():
            lines.append(f"### `{file_path}`\n")
            for f in file_findings:
                emoji = SEVERITY_EMOJI.get(f.severity, "")
                lines.append(
                    f"- {emoji} **{f.rule_id}** (L{f.location.start_line}): {f.title}"
                )
                if f.description and f.description != f.title:
                    lines.append(f"  > {f.description[:200]}")
                if f.suggestion:
                    lines.append(f"  > 💡 **Fix:** {f.suggestion.description[:150]}")
                if f.code_snippet:
                    lines.append(f"\n  ```python\n  {f.code_snippet}\n  ```\n")
            lines.append("")

        return "\n".join(lines)

    def _metrics_section(self, report: ReviewReport) -> str:
        all_metrics = []
        for fa in report.files_analyzed:
            all_metrics.extend(fa.complexity_metrics)

        if not all_metrics:
            return ""

        high_risk = [m for m in all_metrics if m.risk_level in ("medium", "high")]
        if not high_risk:
            return ""

        lines = [
            "## Complexity Metrics\n",
            "| Function | CC | Cognitive | LOC | Risk |",
            "|----------|---:|----------:|----:|------|",
        ]

        for m in sorted(high_risk, key=lambda x: x.cyclomatic_complexity, reverse=True)[:10]:
            lines.append(
                f"| `{m.function_name}` | {m.cyclomatic_complexity} | "
                f"{m.cognitive_complexity} | {m.lines_of_code} | {m.risk_level} |"
            )

        return "\n".join(lines)

    def _footer(self, report: ReviewReport) -> str:
        return (
            "---\n"
            f"*Generated by [CodeVigil](https://github.com/Aliyaan-a/CodeVigil-Always-On-AI-Code-Review-Agent) "
            f"in {report.analysis_duration_ms:.0f}ms*"
        )
